#!/usr/bin/env python3
"""
gen_callhierarchy_code.py  –  Generate synthetic C++ call graphs for
                               clangd CallHierarchyBenchmark.

Topologies
----------
chain   – linear chain: f0->f1->f2->...->fN-1
          target: middle function (N/2)  → 1 caller, 1 callee

hub     – star/fan-in: N callers all call hub_function()
          target: hub_function           → N callers, 0 direct callees

fanout  – star/fan-out: hub_function calls N callees
          target: hub_function           → 0 callers, N callees

tree    – binary call tree of depth D (2^D leaves)
          target: root                   → 0 callers, 2^D-1 indirect callees

mixed   – hub_function has both N callers AND M callees
          target: hub_function           → N callers, M callees

Usage
-----
python3 gen_callhierarchy_code.py \\
    --topology hub --callers 1000 --output /tmp/bench_hub.cpp

python3 gen_callhierarchy_code.py \\
    --topology chain --size 10000 --output /tmp/bench_chain.cpp

python3 gen_callhierarchy_code.py \\
    --topology mixed --callers 500 --callees 500 --output /tmp/bench_mixed.cpp
"""

import argparse
import sys
from pathlib import Path


# ─── helpers ─────────────────────────────────────────────────────────────────

def _header(out, description: str):
    out.append("// AUTO-GENERATED by gen_callhierarchy_code.py")
    out.append(f"// Topology: {description}")
    out.append("// Compile with: clangd-indexer <file> -- > <file>.dex")
    out.append("")
    out.append("// Prevent the optimiser from eliminating empty call chains.")
    out.append("extern void __sink(int);")
    out.append("")


def _footer(out, target: str):
    out.append("")
    out.append("// Entry point so the TU is a valid translation unit.")
    out.append("int main() {")
    out.append(f"    {target}();")
    out.append("    return 0;")
    out.append("}")


# ─── topologies ──────────────────────────────────────────────────────────────

def gen_chain(n: int) -> tuple[str, list[str]]:
    """f0 -> f1 -> ... -> f(n-1).  Target: f(n//2)."""
    lines: list[str] = []
    _header(lines, f"chain  size={n}  target=f{n // 2}")

    # Forward declarations
    for i in range(n):
        lines.append(f"void f{i}();")
    lines.append("")

    # Definitions
    for i in range(n):
        lines.append(f"void f{i}() {{")
        if i + 1 < n:
            lines.append(f"    f{i + 1}();")
        else:
            lines.append("    __sink(0);")
        lines.append("}")
    lines.append("")

    target = f"f{n // 2}"
    _footer(lines, target)
    return target, lines


def gen_hub(n_callers: int) -> tuple[str, list[str]]:
    """N callers each call hub_function().  Target: hub_function."""
    lines: list[str] = []
    _header(lines, f"hub (fan-in)  callers={n_callers}  target=hub_function")

    lines.append("void hub_function();")
    for i in range(n_callers):
        lines.append(f"void caller{i}();")
    lines.append("")

    lines.append("void hub_function() { __sink(42); }")
    lines.append("")
    for i in range(n_callers):
        lines.append(f"void caller{i}() {{ hub_function(); }}")
    lines.append("")

    _footer(lines, "hub_function")
    return "hub_function", lines


def gen_fanout(n_callees: int) -> tuple[str, list[str]]:
    """hub_function calls N callees.  Target: hub_function."""
    lines: list[str] = []
    _header(lines, f"fanout  callees={n_callees}  target=hub_function")

    for i in range(n_callees):
        lines.append(f"void callee{i}();")
    lines.append("void hub_function();")
    lines.append("")

    for i in range(n_callees):
        lines.append(f"void callee{i}() {{ __sink({i}); }}")
    lines.append("")
    lines.append("void hub_function() {")
    for i in range(n_callees):
        lines.append(f"    callee{i}();")
    lines.append("}")
    lines.append("")

    _footer(lines, "hub_function")
    return "hub_function", lines


def gen_tree(depth: int) -> tuple[str, list[str]]:
    """Full binary call tree of the given depth.  Target: node_0 (root)."""
    lines: list[str] = []
    n = (1 << (depth + 1)) - 1  # total nodes
    _header(lines, f"binary-tree  depth={depth}  nodes={n}  target=node_0")

    for i in range(n):
        lines.append(f"void node{i}();")
    lines.append("")

    for i in range(n):
        left = 2 * i + 1
        right = 2 * i + 2
        lines.append(f"void node{i}() {{")
        if left < n:
            lines.append(f"    node{left}();")
        if right < n:
            lines.append(f"    node{right}();")
        if left >= n:
            lines.append(f"    __sink({i});")
        lines.append("}")
    lines.append("")

    _footer(lines, "node0")
    return "node0", lines


def gen_mixed(n_callers: int, n_callees: int) -> tuple[str, list[str]]:
    """hub_function is called by N callers AND calls M callees."""
    lines: list[str] = []
    _header(lines,
            f"mixed  callers={n_callers}  callees={n_callees}  "
            f"target=hub_function")

    for i in range(n_callers):
        lines.append(f"void caller{i}();")
    for i in range(n_callees):
        lines.append(f"void callee{i}();")
    lines.append("void hub_function();")
    lines.append("")

    for i in range(n_callees):
        lines.append(f"void callee{i}() {{ __sink({i}); }}")
    lines.append("")

    lines.append("void hub_function() {")
    for i in range(n_callees):
        lines.append(f"    callee{i}();")
    lines.append("}")
    lines.append("")

    for i in range(n_callers):
        lines.append(f"void caller{i}() {{ hub_function(); }}")
    lines.append("")

    _footer(lines, "hub_function")
    return "hub_function", lines


# ─── multi-TU scenario ────────────────────────────────────────────────────────

def gen_multi_tu(n_modules: int, callers_per_module: int,
                 out_dir: Path) -> tuple[str, list[Path]]:
    """
    Generate N separate .cpp files each containing <callers_per_module>
    callers that all call a common hub_function declared in a shared header.
    Returns the target function name and the list of generated file paths.
    """
    out_dir.mkdir(parents=True, exist_ok=True)
    files: list[Path] = []

    # Shared header
    hdr = out_dir / "hub.h"
    hdr.write_text("// AUTO-GENERATED\nextern void hub_function();\n")
    files.append(hdr)

    # hub implementation
    impl = out_dir / "hub.cpp"
    impl.write_text(
        '// AUTO-GENERATED\n'
        '#include "hub.h"\n'
        'extern void __sink(int);\n'
        'void hub_function() { __sink(99); }\n'
    )
    files.append(impl)

    # N caller modules
    for m in range(n_modules):
        src = out_dir / f"module{m}.cpp"
        lines = [
            '// AUTO-GENERATED',
            '#include "hub.h"',
            '',
        ]
        for i in range(callers_per_module):
            lines.append(
                f'void module{m}_caller{i}() {{ hub_function(); }}'
            )
        src.write_text('\n'.join(lines) + '\n')
        files.append(src)

    return "hub_function", files


# ─── main ─────────────────────────────────────────────────────────────────────

def main():
    p = argparse.ArgumentParser(
        description=__doc__,
        formatter_class=argparse.RawDescriptionHelpFormatter,
    )
    p.add_argument(
        "--topology", "-t",
        choices=["chain", "hub", "fanout", "tree", "mixed", "multi-tu"],
        default="hub",
        help="Call graph shape (default: hub)",
    )
    p.add_argument("--size", "-n", type=int, default=1000,
                   help="Generic size parameter (chain length / tree nodes)")
    p.add_argument("--callers", type=int, default=500,
                   help="Number of callers  (hub / mixed / multi-tu)")
    p.add_argument("--callees", type=int, default=500,
                   help="Number of callees  (fanout / mixed)")
    p.add_argument("--depth", "-d", type=int, default=10,
                   help="Tree depth (tree topology)")
    p.add_argument("--modules", "-m", type=int, default=10,
                   help="Number of translation units (multi-tu topology)")
    p.add_argument("--output", "-o", default="-",
                   help="Output .cpp file path, or directory for multi-tu "
                        "(default: stdout)")
    args = p.parse_args()

    if args.topology == "multi-tu":
        out_dir = Path(args.output) if args.output != "-" else Path("/tmp/bench_multi_tu")
        target, files = gen_multi_tu(
            n_modules=args.modules,
            callers_per_module=args.callers,
            out_dir=out_dir,
        )
        total_callers = args.modules * args.callers
        print(f"Generated {len(files)} files in {out_dir}/")
        print(f"Target function  : {target}")
        print(f"Total callers    : {total_callers}")
        print()
        print("Index all files with:")
        cpp_files = " ".join(str(f) for f in files if f.suffix == ".cpp")
        print(f"  for f in {cpp_files}; do")
        print(f"      clangd-indexer $f -- -I{out_dir} >> {out_dir}/combined.dex")
        print(f"  done")
        print()
        print("Then benchmark:")
        print(f"  CallHierarchyBenchmark {out_dir}/combined.dex {target} "
              "--benchmark_min_time=0.1s")
        return

    # Single-file topologies
    if args.topology == "chain":
        target, lines = gen_chain(args.size)
    elif args.topology == "hub":
        target, lines = gen_hub(args.callers)
    elif args.topology == "fanout":
        target, lines = gen_fanout(args.callees)
    elif args.topology == "tree":
        target, lines = gen_tree(args.depth)
    elif args.topology == "mixed":
        target, lines = gen_mixed(args.callers, args.callees)
    else:
        p.error(f"Unknown topology: {args.topology}")

    code = "\n".join(lines) + "\n"

    if args.output == "-":
        sys.stdout.write(code)
    else:
        Path(args.output).write_text(code)
        print(f"Written {len(lines)} lines to {args.output}")
        print(f"Target function : {target}")
        print()
        print("Next steps:")
        print(f"  clangd-indexer {args.output} -- > {args.output}.dex")
        print(f"  CallHierarchyBenchmark {args.output}.dex {target} "
              "--benchmark_min_time=0.1s")


if __name__ == "__main__":
    main()
